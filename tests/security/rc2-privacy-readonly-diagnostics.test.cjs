'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {classifySecureManagementOperation}=require('../../utils/rc2-management-safety-policy.cjs');
const {readExistingBundleDiagnostics}=require('../../utils/rc2-readonly-bundle-diagnostics.cjs');
const base='/devproxy/api';
function classify(method,route,flags={}){
 return classifySecureManagementOperation({method,pathname:base+route,base,nodeEnv:'production',...flags});
}
function fixture(fn){
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'rc2-get-purity-'));
 try{return fn(dir);}finally{fs.rmSync(dir,{force:true,recursive:true});}
}
for(const route of ['/ai/reindex','/ai/thoughts/inject']){
 test('RED: production deny egress/debug '+route,()=>{
  assert.equal(classify('POST',route,{allowFlag:'1',denyFlag:'0'}).blocked,true);
 });
 test('RED: HMAC-spool deny egress/debug '+route,()=>{
  assert.equal(classify('POST',route,{nodeEnv:'development',spoolDirectory:'/private/spool'}).blocked,true);
 });
}
for(const [method,route] of [['GET','/ai/health'],['GET','/apps/list'],
 ['POST','/apps/install'],['POST','/apps/create-route'],['POST','/apps/regenerate']]){
 test('preserve transactional/read route '+route,()=>{
  assert.equal(classify(method,route).blocked,false);
 });
}
test('RED: existing diagnostics is read-only, byte-stable and complete',()=>fixture(dir=>{
 const file=path.join(dir,'bundle-diagnostics.json');
 const data={included:[{route:'/test'}],skipped:[]};
 fs.writeFileSync(file,JSON.stringify(data));const prior=fs.statSync(file);
 const result=readExistingBundleDiagnostics({file});
 assert.equal(result.code,'BUNDLE_DIAGNOSTICS_OK');
 assert.deepEqual(result.diagnostics,data);
 assert.equal(fs.statSync(file).mtimeMs,prior.mtimeMs);
 assert.deepEqual(fs.readdirSync(dir),['bundle-diagnostics.json']);
}));
test('RED: missing diagnostics is not generated by GET',()=>fixture(dir=>{
 const file=path.join(dir,'bundle-diagnostics.json');
 assert.deepEqual(readExistingBundleDiagnostics({file}),{code:'BUNDLE_DIAGNOSTICS_MISSING'});
 assert.deepEqual(fs.readdirSync(dir),[]);
}));
test('RED: symlinks, hardlinks, malformed and oversized artifacts fail closed',()=>fixture(dir=>{
 const file=path.join(dir,'bundle-diagnostics.json');
 const original=path.join(dir,'original.json');
 fs.writeFileSync(original,'{"included":[]}');fs.symlinkSync(original,file);
 assert.equal(readExistingBundleDiagnostics({file}).code,'BUNDLE_DIAGNOSTICS_UNSAFE');
 fs.unlinkSync(file);fs.linkSync(original,file);
 assert.equal(readExistingBundleDiagnostics({file}).code,'BUNDLE_DIAGNOSTICS_UNSAFE');
 fs.unlinkSync(file);fs.writeFileSync(file,'{bad-json}');
 assert.equal(readExistingBundleDiagnostics({file}).code,'BUNDLE_DIAGNOSTICS_INVALID');
 fs.writeFileSync(file,'x'.repeat(262145));
 assert.equal(readExistingBundleDiagnostics({file}).code,'BUNDLE_DIAGNOSTICS_UNSAFE');
}));
test('RED: no false active list from malformed or missing included',()=>fixture(dir=>{
 const file=path.join(dir,'bundle-diagnostics.json');
 for(const body of ['null','[]','123','{"included":{}}']){
  fs.writeFileSync(file,body);
  assert.equal(readExistingBundleDiagnostics({file}).code,'BUNDLE_DIAGNOSTICS_INVALID');
 }
}));
test('RED: both GET handlers use read-only reader without spawning bundle generation',()=>{
 const api=fs.readFileSync(path.join(__dirname,'../../utils/proxyConfigAPI.js'),'utf8');
 const a=api.indexOf("if (req.method === 'GET' && u.pathname === apiPath('apps/diagnostics'))");
 const b=api.indexOf("if (req.method === 'POST' && u.pathname === apiPath('apps/regenerate'))",a);
 assert.ok(a>0&&b>a);
 const section=api.slice(a,b);
 assert.equal((section.match(/readExistingBundleDiagnostics\(/g)||[]).length,2);
 assert.equal(/spawnSync|execSync|generateAppsBundle|writeFileSync|unlinkSync/.test(section),false);
 assert.match(api,/require\('\.\/rc2-readonly-bundle-diagnostics\.cjs'\)/);
});
